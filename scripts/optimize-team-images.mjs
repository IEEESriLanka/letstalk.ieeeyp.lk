import { mkdir, readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import path from "node:path";
import { loadEnv } from "vite";
import { createClient } from "@supabase/supabase-js";
import sharp from "sharp";

const env = { ...loadEnv("development", process.cwd(), ""), ...process.env };
const client = createClient(env.VITE_SUPABASE_URL, env.VITE_SUPABASE_PUBLISHABLE_KEY, {
  auth: { persistSession: false, autoRefreshToken: false },
});
const { data, error } = await client.from("site_content").select("content").eq("id", "site").single();
if (error) throw error;
const team = data.content.teamPage;
const members = [...(team.currentMembers ?? []), ...(team.yearlyTeams ?? []).flatMap((year) => year.members)];
const urls = [...new Set(members.map((member) => member.imageUrl).filter(Boolean))];
const directory = path.resolve("public/team/optimized");
await mkdir(directory, { recursive: true });
const manifest = {};
let originalBytes = 0;
let optimizedBytes = 0;
// Process sequentially to keep memory use bounded with large source photos.
for (const [index, url] of urls.entries()) {
  let buffer;
  if (url.startsWith("/team/")) {
    const filename = path.resolve("public", `.${url}`);
    if (!filename.startsWith(path.resolve("public/team") + path.sep)) throw new Error("Invalid team image path");
    buffer = await readFile(filename);
  } else {
    const parsed = new URL(url);
    if (parsed.origin !== new URL(env.VITE_SUPABASE_URL).origin || !parsed.pathname.startsWith("/storage/v1/object/public/")) {
      throw new Error("Team image must be a local team photo or public project storage URL");
    }
    const response = await fetch(url, { signal: AbortSignal.timeout(30000) });
    if (!response.ok) throw new Error(`Photo download failed: HTTP ${response.status}`);
    buffer = Buffer.from(await response.arrayBuffer());
  }
  const hash = createHash("sha256").update(buffer).digest("hex").slice(0, 20);
  const variants = [];
  for (const width of [320, 640, 960]) {
    const { data: image, info } = await sharp(buffer).rotate()
      .resize({ width, withoutEnlargement: true }).webp({ quality: 78, effort: 5 })
      .toBuffer({ resolveWithObject: true });
    if (variants.some((variant) => variant.width === info.width)) continue;
    const src = `/team/optimized/${hash}-${info.width}.webp`;
    await writeFile(path.join(directory, path.basename(src)), image);
    variants.push({ src, width: info.width, height: info.height, bytes: image.length });
  }
  const preferred = variants.find((variant) => variant.width >= 640) ?? variants.at(-1);
  manifest[url] = {
    src: preferred.src,
    srcSet: variants.map((variant) => `${variant.src} ${variant.width}w`).join(", "),
    width: preferred.width,
    height: preferred.height,
  };
  originalBytes += buffer.length;
  optimizedBytes += preferred.bytes;
  console.log(`Photo ${index + 1}/${urls.length}: ${Math.round(buffer.length / 1024)} KB → ${Math.round(preferred.bytes / 1024)} KB`);
}
await writeFile("src/lib/team-image-manifest.ts",
  `// Generated by npm run optimize:team. Originals remain in storage.\nexport const teamImageManifest: Record<string, { src: string; srcSet: string; width: number; height: number }> = ${JSON.stringify(manifest, null, 2)};\n`);
console.log(`Total: ${(originalBytes / 1048576).toFixed(2)} MB → ${(optimizedBytes / 1048576).toFixed(2)} MB (${Math.round((1 - optimizedBytes / originalBytes) * 100)}% smaller at 640px)`);
